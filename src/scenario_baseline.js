/* 项目演练模式：已结束/归档项目按基础版留存，演练中项目采用实战版 */
const PROJECT_MODE = {
  'P2026-012': '基础版',
  'P2026-011': '基础版',
  'P2026-010': '实战版',
  'P2026-009': '基础版'
};

function bump(v) {
  const m = /^v(\d+)\.(\d+)$/.exec(String(v || 'v1.0'));
  return m ? 'v' + m[1] + '.' + (Number(m[2]) + 1) : 'v1.1';
}

/* 将基线写入数据库：覆盖各场景节点，并同步节点数与版本号 */
function apply(db, opts) {
  opts = opts || {};
  const now = new Date();
  const pad = function (n) { return n < 10 ? '0' + n : String(n); };
  const today = now.getFullYear() + '-' + pad(now.getMonth() + 1) + '-' + pad(now.getDate());
  const del = db.prepare('DELETE FROM script_nodes WHERE scenario_id=?');
  const ins = db.prepare('INSERT INTO script_nodes (id,scenario_id,type,title,target,time,timeout,form,att,descr,branches,seq,guide,keywords,action,required) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)');
  const out = [];
  Object.keys(SCEN).forEach(function (sid) {
    const sc = db.prepare('SELECT * FROM scenarios WHERE id=?').get(sid);
    if (!sc) return;
    const steps = SCEN[sid];
    del.run(sid);
    steps.forEach(function (r, i) {
      ins.run(sid + '-' + (i + 1), sid, r[0], r[1], r[2], r[3], r[4] || null, '', '', r[6] || '',
        JSON.stringify([]), i, r[7] || '', r[8] || '', r[9] || '', r[5] ? 1 : 0);
    });
    const version = opts.bump === false ? (sc.version || 'v1.0') : bump(sc.version);
    db.prepare('UPDATE scenarios SET nodes=?, version=?, updated=? WHERE id=?')
      .run(steps.length, version, opts.date || today, sid);
    out.push({ id: sid, nodes: steps.length, version: version });
  });
  /* 项目演练模式 */
  Object.keys(PROJECT_MODE).forEach(function (pid) {
    const p = db.prepare('SELECT id FROM projects WHERE id=?').get(pid);
    if (p) db.prepare('UPDATE projects SET mode=? WHERE id=?').run(PROJECT_MODE[pid], pid);
  });
  /* 未指定模式的历史项目默认基础版 */
  db.prepare("UPDATE projects SET mode='基础版' WHERE mode IS NULL OR mode=''").run();
  return out;
}

module.exports = { SCEN, PROJECT_MODE, apply, bump };
