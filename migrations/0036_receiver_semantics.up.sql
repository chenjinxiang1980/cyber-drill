-- 0036 接收人语义统一（P1-02 / P1-14 / P1-15）
-- 对外上报节点的 receiver 统一为实际接收单位；院内部署的报案节点 receiver 为院应急指挥部，
-- 对外提交对象写入节点说明，避免「口径已上报给市网信办，节点却让信息科接收」的自相矛盾。
-- 同时给 S03-8 补运营商清洗工单证据，落实 P1-15。
-- 纯 DML，固定终值，可重复执行。

-- 对外双报：节点接收方 = 对应主管部门
UPDATE script_nodes SET receiver = '市卫生健康局' WHERE id IN ('S02-8','S03-6','S04-7','S05-6','S06-6');
UPDATE script_nodes SET receiver = '市网信办'     WHERE id IN ('S02-9','S03-7','S04-8','S05-7','S06-7');

-- S06 对外上报不再把医务处当作接收方，改为内部抄送
UPDATE script_nodes
   SET descr = '按重大事件 1 小时时限向市卫生健康局报告事件等级、泄露数据范围与舆情情况，并留存上报回执。院内抄送：医务处（患者沟通）、院办（口径会签）。'
 WHERE id = 'S06-6';
UPDATE script_nodes
   SET descr = '按 1 小时时限向市网信办报告事件等级、泄露数据范围与舆情情况，样本先固定哈希后提交。院内抄送：医务处（患者沟通）、院办（口径会签）。'
 WHERE id = 'S06-7';

-- 报案节点：院内承办与对外提交分离
UPDATE script_nodes
   SET receiver = '院应急指挥部',
       descr = '由信息科负责人承办，向市网安大队提交报案材料（事件经过、受影响系统、已保全证据、联系人）；回执仅作归档，不作为后续节点或结束的前置条件。'
 WHERE id = 'S01-15';

-- S03-8：运营商协同需留工单/清洗回执，并把结果交信息科负责人
