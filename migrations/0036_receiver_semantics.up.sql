   SET receiver = '信息科负责人',
       evidence_req = '[{"type":"操作日志","name":"网络设备/防火墙操作日志","note":""},{"type":"处置记录","name":"隔离处置记录","note":""},{"type":"附件","name":"运营商工单/流量清洗回执","note":"联系运营商或云清洗的工单编号、处置时段与回执截图"}]'
 WHERE id = 'S03-8';
