   SET evidence_req = '[{"type":"表单文书","name":"升级研判记录","note":"含维持/升级结论、事实依据（引用原研判节点已采集的系统/数据/患者安全/扩散事实）、触发条件与报批时间"},{"type":"上报材料","name":"升级续报与回执","note":"升级时含新等级、补报对象、时间与接收回执；维持时注明观察时限"}]'
 WHERE id IN ('S02-3A','S06-3A','S08-3A');
