-- 依据：
--   1) S03-8A 是对外协同节点，按 0036 口径 receiver 应写实际接收单位（运营商），
--      与责任角色区分；责任角色仍为 信息科负责人（对外协调），
--      网络安全管理员在院内提供出口链路与清洗策略信息（配合，不单独设节点）。
