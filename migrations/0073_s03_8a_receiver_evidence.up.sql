-- S03-8A 对外接收方 + 责任分工写实
UPDATE script_nodes
   SET receiver = '运营商',
       descr = '院内清洗策略生效后，由网络安全管理员提供出口链路与清洗策略信息；信息科负责人联系运营商确认出口链路、上游清洗能力与封禁范围，提交清洗/封禁工单，留存工单编号、处置时段与回执。先内后外：不得以运营商处置替代院内兜底与取证。'
 WHERE id = 'S03-8A';

