-- 0011_script_node_quality_rules.up.sql
-- 剧本节点级「处置文字质量规则」
-- ---------------------------------------------------------------------
-- 背景：
--   自动评分此前只做「关键词命中 ≥2」与证据子串匹配，且关键词把表单填写值
--   也算进去，导致「把关键词塞进表单」就能满分；同时 evidence_req='[]'
--   的节点仍被扣 20%。本次把质量口径下沉为节点可配置规则，由剧本编排
--   「节点配置」侧边栏维护。
--
-- 变更：
--   仅新增一列 script_nodes.quality_rules（TEXT，存 JSON），不改动任何
--   现有列与既有数据。老节点该列为 NULL，评分时自动回落到默认口径：
--     · 必含关键词未配置 → 沿用旧口径 keywords + 命中≥2；
--     · 最小长度 15/10 字、要素「对象+动作+结论」、敷衍词黑名单；
--     · evidence_req 为空或 "[]" 视为无取证要求，不再扣分。
--
-- 幂等：
--   由 schema_migrations 保证只执行一次；手工重复执行会因列已存在报错。
--
-- 回滚方式（人工执行）：
--   ALTER TABLE script_nodes DROP COLUMN quality_rules;
-- =====================================================================
SET NAMES utf8mb4;

ALTER TABLE script_nodes
  ADD COLUMN quality_rules TEXT DEFAULT NULL
  COMMENT '处置文字质量规则 JSON：必含/加分关键词、最小长度、要素要求、敷衍词、扣分比例'
  AFTER keywords;
